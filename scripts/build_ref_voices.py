#!/usr/bin/env python3
# coding=utf-8
"""从提取好的 x-vector 生成两份产物：

1. **C++ 头文件** ``qwen3tts_speaker_embed.h``
   (``std::unordered_map<std::string, std::vector<float>>``)
2. **Python SDK 的 base64 字典块**
   (``wdnai/backends/tts.py`` 的 ``_BUNDLED_SPEAKER_EMBEDDINGS_B64``)

编码链（两份产物完全一致）
--------------------------
    float32 → fp16 → (C++: "{:.8e}f" 字面量 / Python: zlib.compress(level=7) → base64)

为什么先量成 fp16
------------------
C++ 侧存的是字面量，Python 侧存的是 fp16 的原始字节 —— 两边必须
是**同一个量化结果**，否则「同一份音色」在 C++ demo 和 webui 里会
有细微差别。所以统一先 fp16 量化，再各自编码。

头文件格式与 model zoo 的 ``export_speaker_embed_hpp.py`` 逐行一致
（每行 8 个数、缩进 4 空格、条目行 ``  {"name", {`` … ``  }},``），
这样以后再用官方脚本 ``--ref_audio`` 追加条目时格式不会打架。

用法
----
    .venv/bin/python -u scripts/build_ref_voices.py \
        --npy-dir /home/rockchip/ref_voices/out \
        --map "lovely_girl=甜美萝莉音.npy,male_announcer=男播音员音.npy,..." \
        --header /tmp/out/qwen3tts_speaker_embed.h \
        --blob   /tmp/out/blob.py
"""
from __future__ import annotations

import argparse
import base64
import json
import sys
import zlib
from pathlib import Path

import numpy as np

EMBED_DIM = 2048
ITEMS_PER_LINE = 8


def parse_map(text: str) -> list[tuple[str, str]]:
    """``"id=a.npy,id2=b.npy"`` → ``[("id", "a.npy"), ...]``。"""
    out = []
    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        vid, _, fname = item.partition("=")
        vid = vid.strip()
        fname = fname.strip()
        if not vid:
            raise ValueError(f"映射项 {item!r} 缺少 id")
        out.append((vid, fname or f"{vid}.npy"))
    return out


def load_vectors(npy_dir: Path, mapping) -> "dict[str, np.ndarray]":
    out = {}
    for vid, fname in mapping:
        p = npy_dir / fname
        if not p.is_file():
            raise FileNotFoundError(f"缺少 x-vector: {p}")
        vec = np.load(str(p)).astype(np.float32).reshape(-1)
        if vec.shape[0] != EMBED_DIM:
            raise ValueError(f"{vid}: 维度应为 {EMBED_DIM}，实得 {vec.shape[0]}")
        if not bool(np.all(np.isfinite(vec))):
            raise ValueError(f"{vid}: 向量含 NaN/Inf")
        out[vid] = vec
    return out


def quantize_fp16(vec: np.ndarray) -> np.ndarray:
    """float32 → fp16 → 再读回 float32。

    两份产物都以这个结果为源，所以 C++ 和 Python 侧看到的是同一组数。
    """
    return np.asarray(vec, dtype=np.float32).astype(np.float16).astype(np.float32)


def emit_header(vectors: "dict[str, np.ndarray]") -> str:
    """生成 C++ 头文件内容。"""
    lines = [
        "#pragma once",
        "#include <unordered_map>",
        "#include <vector>",
        "#include <string>",
        "",
        "// Auto-generated by export_speaker_embed_hpp.py",
        "// Values are fp16-quantized x-vectors (2048-d) from the RKNN speaker encoder.",
        "",
        "const std::unordered_map<std::string, std::vector<float>> speaker_embeddings = {",
    ]
    items = list(vectors.items())
    for idx, (name, vec) in enumerate(items):
        suffix = "," if idx < len(items) - 1 else ""
        lines.append('  {{"{}", {{'.format(name))
        q = quantize_fp16(vec)
        for i in range(0, len(q), ITEMS_PER_LINE):
            chunk = ", ".join("{:.8e}f".format(float(v)) for v in q[i:i + ITEMS_PER_LINE])
            lines.append("    " + chunk + ",")
        lines.append("  }}" + suffix)
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def emit_blob(vectors: "dict[str, np.ndarray]") -> str:
    """生成 SDK 里那张表的 Python 代码块。

    编码链与 ``scripts/tts_pack_speaker_embeds.py`` 完全一致
    （float32 → fp16 → zlib.compress(level=7) → base64），
    所以两条独立路径算出来的字符串应当**逐字节相同**。
    """
    lines = ["_BUNDLED_SPEAKER_EMBEDDINGS_B64: dict[str, tuple[str, ...]] = {"]
    for name, vec in vectors.items():
        raw = quantize_fp16(vec).astype(np.float16).tobytes()
        blob = base64.b64encode(zlib.compress(raw, 7)).decode("ascii")
        lines.append(f'    "{name}": (')
        lines.append(f'        "{blob}",')
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--npy-dir", required=True, help="x-vector 目录")
    ap.add_argument("--map", required=True, help="id=文件名.npy 逗号分隔")
    ap.add_argument("--header", help="C++ 头文件输出路径")
    ap.add_argument("--blob", help="SDK base64 字典块输出路径")
    ap.add_argument("--json-out", help="元信息 JSON 输出路径")
    args = ap.parse_args()

    mapping = parse_map(args.map)
    vectors = load_vectors(Path(args.npy_dir), mapping)
    print(f"读到 {len(vectors)} 条 x-vector:")
    for name, vec in vectors.items():
        q = quantize_fp16(vec)
        err = float(np.abs(q - vec).max())
        print(f"  {name:<20} dim={vec.shape[0]} norm={np.linalg.norm(vec):.4f} "
              f"fp16 量化最大误差 {err:.3e}")

    if args.header:
        Path(args.header).parent.mkdir(parents=True, exist_ok=True)
        Path(args.header).write_text(emit_header(vectors), encoding="utf-8")
        print(f"\n已写头文件 {args.header}")
    if args.blob:
        Path(args.blob).parent.mkdir(parents=True, exist_ok=True)
        Path(args.blob).write_text(emit_blob(vectors) + "\n", encoding="utf-8")
        print(f"已写 base64 块 {args.blob}")
    if args.json_out:
        meta = {
            name: {
                "dim": int(vec.shape[0]),
                "norm": round(float(np.linalg.norm(vec)), 6),
                "fp16_max_err": round(
                    float(np.abs(quantize_fp16(vec) - vec).max()), 8),
            }
            for name, vec in vectors.items()
        }
        Path(args.json_out).write_text(
            json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"已写元信息 {args.json_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
